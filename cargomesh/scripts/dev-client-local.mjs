import fs from 'node:fs/promises';
import http from 'node:http';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
if (process.env.NODE_ENV === 'production') throw new Error('Local Client profile requires development.');
const filename=process.env.CARGOMESH_HAC52_ACCESS_FILE;
if (!filename || !path.isAbsolute(filename)) throw new Error('Private access file path required.');
const config=JSON.parse(await fs.readFile(filename,'utf8'));
if(config.profile!=='hac52-client'||config.url!=='http://127.0.0.1:64621'||config.appOrigin!=='http://127.0.0.1:59580')throw new Error('Invalid HAC-52 local profile.');
process.env.NODE_ENV='development';
process.env.CARGOMESH_LOCAL_PROFILE='hac52-client';
process.env.NEXT_PUBLIC_SUPABASE_URL=config.url;
process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY=config.anonKey;
process.env.CM_ENABLE_DEMO='0';
process.env.CARGOMESH_ASSIGNED_DEMO_ENABLED='false';
process.env.CARGOMESH_LOCAL_CLIENT_PREVIEW_ENABLED='false';
process.env.CARGOMESH_LOCAL_LOGIN_DEFAULTS_ENABLED='false';
const dir=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
process.chdir(dir);
const {default:next}=await import('next');
const app=next({dev:true,dir,hostname:'127.0.0.1',port:59580});
await app.prepare();
const server=http.createServer(app.getRequestHandler());
server.on('upgrade',(req,socket,head)=>app.getUpgradeHandler()(req,socket,head).catch(()=>socket.destroy()));
server.listen(59580,'127.0.0.1',()=>console.log('HAC-52 connected Client (synthetic local data): http://127.0.0.1:59580/api/local/hac52/client-session'));
